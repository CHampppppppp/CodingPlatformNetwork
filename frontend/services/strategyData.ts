/**
 * 依据学习投入、学习方法倾向、学习态度三个维度推断学习风格。
 * - 三个维度均 ≥4：活跃型
 * - 三个维度均 ≤2：沉思型
 * - 其他：两者兼备
 */
export function inferLearningStyle(
  attributes: CognitiveAttributes,
): LearningStyle {
  const inputs = [
    attributes.learningEngagement,
    attributes.learningMethod,
    attributes.learningAttitude,
  ];
  const allHigh = inputs.every((v) => v >= 4);
  const allLow = inputs.every((v) => v <= 2);

  if (allHigh) return "active";
  if (allLow) return "reflective";
  return "balanced";
}
